const BY_CODE = new Map(STATES.map((s) => [s.code, s]));

// Accepts a two-digit code or a state name (case/space tolerant).
function resolveState(value) {
  const raw = String(value == null ? '' : value).trim();
  if (!raw) return null;
  const byCode = BY_CODE.get(raw.padStart(2, '0'));
  if (byCode) return byCode;
  const lower = raw.toLowerCase();
  return STATES.find((s) => s.name.toLowerCase() === lower) || null;
}

module.exports = { STATES, resolveState };
