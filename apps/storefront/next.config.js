// Resolve the server-side API base inline: `next start` loads this file at boot, and the
// production image only ships .next/public/package.json, so a require() of app code
// (lib/serverApiBase.cjs) would crash the container with MODULE_NOT_FOUND.
// Browser and server need different bases in a container deploy:
//   NEXT_PUBLIC_BACKEND_URL -> what the browser uses (often "/api")
//   BACKEND_INTERNAL_URL    -> what the server uses for rewrites (e.g. http://backend:9000)
function resolveBackendBase(env = process.env) {
  const absolute = (v) => {
    const s = String(v || '').trim();
    return /^https?:\/\//i.test(s) ? s.replace(/\/+$/, '') : null;
  };
  return absolute(env.BACKEND_INTERNAL_URL) || absolute(env.NEXT_PUBLIC_BACKEND_URL) || 'http://localhost:9000';
}

const BACKEND = resolveBackendBase();

const nextConfig = {
  images: {
    unoptimized: true
  },
  env: {
    NEXT_PUBLIC_BACKEND_URL: process.env.NEXT_PUBLIC_BACKEND_URL,
    NEXT_PUBLIC_RAZORPAY_KEY_ID: process.env.NEXT_PUBLIC_RAZORPAY_KEY_ID,
    NEXT_PUBLIC_STORE_NAME: process.env.NEXT_PUBLIC_STORE_NAME
  },
  // The sitemap is generated by the backend; serve it from the storefront origin so
  // /sitemap.xml works whether you deploy one domain (nginx /api) or two subdomains.
  async rewrites() {
    const list = [{ source: '/sitemap.xml', destination: `${BACKEND}/sitemap.xml` }];
    // Single-domain builds use NEXT_PUBLIC_BACKEND_URL=/api and rely on nginx in
    // production. Proxying /api here too means `next start` works standalone (local E2E,
    // previews) instead of returning 404s for every API call.
    if (!/^https?:\/\//i.test(String(process.env.NEXT_PUBLIC_BACKEND_URL || ''))) {
      list.push({ source: '/api/:path*', destination: `${BACKEND}/:path*` });
    }
    return list;
  }
};

module.exports = nextConfig;
